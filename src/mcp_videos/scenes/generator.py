def build_scene_prompt(
    title: str,
    words: Sequence[object] | None = None,
    start_ms: int = DEFAULT_START_MS,
    end_ms: int = DEFAULT_END_MS,
    *,
    subtitle: str = "",
    eyebrow: str = DEFAULT_EYEBROW,
    width: int = DEFAULT_WIDTH,
    height: int = DEFAULT_HEIGHT,
    theme: str = DEFAULT_THEME,
    metrics: Sequence[object] | Mapping[str, Any] | None = None,
    instructions: str = "",
    words_are_absolute: bool | None = None,
) -> str:
    """Build the user prompt with the exact word cues of one scene."""

    if end_ms <= start_ms:
        raise ValueError("end_ms debe ser mayor que start_ms")

    cues = normalize_word_cues(
        words,
        start_ms,
        end_ms,
        absolute=words_are_absolute,
    )
    duration_ms = end_ms - start_ms
    cue_lines = [
        (
            f"- [{_format_seconds(cue['start_ms'])}, {_format_seconds(cue['end_ms'])}] "
            f"{cue['word']!r}"
        )
        for cue in cues
    ]
    if not cue_lines:
        cue_lines.append("- Sin cues de palabra para este intervalo.")

    metric_payload = _normalize_metrics(metrics)
    sections = [
        f"Título de la escena: {title}",
        f"Subtítulo de apoyo: {subtitle or '(sin subtítulo)'}",
        f"Kicker superior: {eyebrow}",
        f"Intervalo absoluto del proyecto: [{start_ms}, {end_ms}] ms",
        f"Duración local de la escena: {duration_ms} ms",
        f"Viewport: {width}x{height} px · tema: {theme}",
        "",
        "word_timestamps locales para sincronizar subtítulos y animaciones:",
        *cue_lines,
        "",
        f"Cues JSON (id={WORD_CUES_SCRIPT_ID}):",
        _json_for_html(cues),
        "",
        "Telemetría sugerida:",
        _json_for_html(metric_payload),
        "",
        "Requisitos obligatorios:",
        "- Documento HTML completo desde <!DOCTYPE html> hasta </html>.",
        "- Sin recursos externos, sin fuentes remotas, sin imágenes de red.",
        "- Todo el movimiento se calcula desde timeMs; nada depende del reloj real.",
        "- window.onFrameTime(timeMs) actualiza SVG, contadores y la palabra activa.",
        "- La palabra activa usa window.MotionKit.activeWordAt/activeWordIndexAt.",
        "- El fondo incluye retícula técnica y el layout respeta 1080x1920.",
        "- Devuelve solo el HTML, sin bloques de código ni comentarios explicativos.",
    ]
    if instructions.strip():
        sections.extend(["", "Instrucciones adicionales:", instructions.strip()])
    return "\n".join(sections)


def _normalize_metrics(
    metrics: Sequence[object] | Mapping[str, Any] | None,
) -> list[dict[str, Any]]:
    if metrics is None:
        return [dict(metric) for metric in DEFAULT_METRICS]

    if isinstance(metrics, Mapping):
        normalized: list[dict[str, Any]] = []
        for label, value in metrics.items():
            if isinstance(value, Mapping):
                item = dict(value)
                item.setdefault("label", str(label))
                normalized.append(_metric_entry(item))
            else:
                normalized.append(_metric_entry({"label": str(label), "value": value}))
        return normalized

    normalized = []
    for item in metrics:
        if isinstance(item, Mapping):
            normalized.append(_metric_entry(dict(item)))
        elif isinstance(item, (tuple, list)):
            payload: dict[str, Any] = {"label": str(item[0]) if item else "MÉTRICA"}
            if len(item) > 1:
                payload["value"] = item[1]
            if len(item) > 2:
                payload["unit"] = item[2]
            normalized.append(_metric_entry(payload))
        else:
            normalized.append(_metric_entry({"label": str(item), "value": ""}))
    return normalized


def _metric_entry(item: dict[str, Any]) -> dict[str, Any]:
    label = str(item.get("label") or item.get("name") or item.get("title") or "MÉTRICA")
    value = item.get("value", item.get("number", ""))
    unit = str(item.get("unit") or "")
    decimals = item.get("decimals")
    if isinstance(decimals, bool) or not isinstance(decimals, int):
        numeric = _read_number({"value": value}, ("value",))
        decimals = 0 if numeric is None or float(numeric).is_integer() else 1
    return {
        "label": label,
        "value": value,
        "unit": unit,
        "decimals": max(0, min(4, int(decimals))),
    }


def _insert_before_closing_tag(html: str, tag: str, snippet: str) -> str:
    lower = html.lower()
    index = lower.rfind(tag)
    if index < 0:
        return html
    return html[:index] + snippet + "\n" + html[index:]


def embed_word_cues(html: str, cues: Sequence[Mapping[str, Any]]) -> str:
    """Guarantee that generated scenes embed their word cues as JSON."""

    if WORD_CUES_SCRIPT_ID in html:
        return html
    payload = _json_for_html([dict(cue) for cue in cues])
    snippet = (
        f'<script type="application/json" id="{WORD_CUES_SCRIPT_ID}" '
        f'data-mcp-word-cues="1">{payload}</script>'
    )
    with_body = _insert_before_closing_tag(html, "</body>", snippet)
    if with_body != html:
        return with_body
    return _insert_before_closing_tag(html, "</html>", snippet)


def _first_not_none(*values: object) -> object:
    for value in values:
        if value is not None:
            return value
    return None


def _normalize_theme(theme: str) -> str:
    return "light" if str(theme).strip().lower() in {"light", "claro", "blanco"} else "dark"


def _normalize_accent(accent: str) -> str:
    value = str(accent).strip()
    return value if _ACCENT_RE.fullmatch(value) else DEFAULT_ACCENT


def build_technical_explainer_scene_html(
    title: str = DEFAULT_SCENE_TITLE,
    words: Sequence[object] | None = None,
    start_ms: int = DEFAULT_START_MS,
    end_ms: int = DEFAULT_END_MS,
    *,
    cues: Sequence[object] | None = None,
    word_timestamps: Sequence[object] | None = None,
    subtitle: str = "",
    eyebrow: str = DEFAULT_EYEBROW,
    duration_ms: int | None = None,
    width: int = DEFAULT_WIDTH,
    height: int = DEFAULT_HEIGHT,
    theme: str = DEFAULT_THEME,
    metrics: Sequence[object] | Mapping[str, Any] | None = None,
    accent: str = DEFAULT_ACCENT,
    words_are_absolute: bool | None = None,
    harness_js: str | None = None,
) -> str:
    """Build a local technical-explainer scene with animated SVG and telemetry."""

    if duration_ms is not None:
        if isinstance(duration_ms, bool) or not isinstance(duration_ms, int) or duration_ms <= 0:
            raise ValueError("duration_ms debe ser un entero > 0")
        end_ms = start_ms + duration_ms
    if isinstance(start_ms, bool) or not isinstance(start_ms, int) or start_ms < 0:
        raise ValueError("start_ms debe ser un entero >= 0")
    if isinstance(end_ms, bool) or not isinstance(end_ms, int) or end_ms <= start_ms:
        raise ValueError("end_ms debe ser mayor que start_ms")
    if isinstance(width, bool) or not isinstance(width, int) or width <= 0:
        raise ValueError("width debe ser un entero > 0")
    if isinstance(height, bool) or not isinstance(height, int) or height <= 0:
        raise ValueError("height debe ser un entero > 0")

    title_text = str(title).strip() or DEFAULT_SCENE_TITLE
    selected_words = _first_not_none(words, cues, word_timestamps)
    normalized_cues = normalize_word_cues(
        selected_words if isinstance(selected_words, Sequence) else None,
        start_ms,
        end_ms,
        absolute=words_are_absolute,
    )
    normalized_metrics = _normalize_metrics(metrics)
    theme_value = _normalize_theme(theme)
    accent_value = _normalize_accent(accent)
    caption_fallback = subtitle.strip() or title_text

    context = {
        "TITLE": html_lib.escape(title_text),
        "SUBTITLE": html_lib.escape(subtitle.strip()),
        "EYEBROW": html_lib.escape(eyebrow.strip() or DEFAULT_EYEBROW),
        "WIDTH": str(width),
        "HEIGHT": str(height),
        "DURATION_MS": str(end_ms - start_ms),
        "START_MS": str(start_ms),
        "THEME": theme_value,
        "ACCENT": accent_value,
        "WORDS_JSON": _json_for_html(normalized_cues),
        "METRICS_JSON": _json_for_html(normalized_metrics),
        "CAPTION_FALLBACK": html_lib.escape(caption_fallback),
        "HARNESS_JS": load_harness_script() if harness_js is None else harness_js,
    }
    return render_template(TECHNICAL_EXPLAINER_TEMPLATE, context)


def _content_from_openai(payload: Mapping[str, Any]) -> str:
    choices = payload.get("choices")
    if not isinstance(choices, Sequence) or not choices:
        return ""
    first = choices[0]
    if not isinstance(first, Mapping):
        return ""
    message = first.get("message")
    if isinstance(message, Mapping):
        content = message.get("content")
        if isinstance(content, str):
            return content
        if isinstance(content, Sequence):
            parts = [
                str(part.get("text", ""))
                for part in content
                if isinstance(part, Mapping) and part.get("type") in {None, "text"}
            ]
            return "".join(parts)
    text = first.get("text")
    return text if isinstance(text, str) else ""


def _content_from_ollama(payload: Mapping[str, Any]) -> str:
    message = payload.get("message")
    if isinstance(message, Mapping):
        content = message.get("content")
        if isinstance(content, str):
            return content
    response = payload.get("response")
    if isinstance(response, str):
        return response
    return _content_from_openai(payload)


def _content_from_anthropic(payload: Mapping[str, Any]) -> str:
    content = payload.get("content")
    if not isinstance(content, Sequence):
        return ""
    parts = [
        str(part.get("text", ""))
        for part in content
        if isinstance(part, Mapping) and part.get("type", "text") == "text"
    ]
    return "".join(parts)


def _content_from_gemini(payload: Mapping[str, Any]) -> str:
    candidates = payload.get("candidates")
    if not isinstance(candidates, Sequence) or not candidates:
        return ""
    first = candidates[0]
    if not isinstance(first, Mapping):
        return ""
    content = first.get("content")
    if not isinstance(content, Mapping):
        return ""
    parts = content.get("parts")
    if not isinstance(parts, Sequence):
        return ""
    return "".join(
        str(part.get("text", "")) for part in parts if isinstance(part, Mapping)
    )


class SceneGenerator:
    """Generate scene HTML with Ollama/vLLM/API providers or local templates."""

    def __init__(
        self,
        settings: AppSettings | None = None,
        *,
        provider: str | None = None,
        model: str | None = None,
        base_url: str | None = None,
        api_key: str | None = None,
        timeout: float = DEFAULT_TIMEOUT_SECONDS,
        http_client: httpx.Client | None = None,
        validator: SceneValidator | None = None,
    ) -> None:
        if timeout <= 0:
            raise ValueError("timeout debe ser > 0")
        self.settings = settings or AppSettings()
        requested = (
            provider
            or os.environ.get("MCP_VIDEOS_LLM_PROVIDER")
            or os.environ.get("LLM_PROVIDER")
            or "ollama"
        )
        self.provider = canonical_provider(requested)
        self.model = model
        self.base_url = base_url
        self.api_key = api_key
        self.timeout = float(timeout)
        self.http_client = http_client
        self.validator = validator

    def _resolved_base_url(self, provider: str) -> str:
        if self.base_url:
            return self.base_url.rstrip("/")
        overrides = {
            "vllm": os.environ.get("VLLM_BASE_URL"),
            "openai": os.environ.get("OPENAI_BASE_URL"),
            "anthropic": os.environ.get("ANTHROPIC_BASE_URL"),
            "gemini": os.environ.get("GEMINI_BASE_URL") or os.environ.get("GOOGLE_BASE_URL"),
        }
        if overrides.get(provider):
            return str(overrides[provider]).rstrip("/")
        if provider == "ollama":
            return self.settings.local_llm_base_url.rstrip("/")
        if provider == "vllm":
            return "http://localhost:8000/v1"
        if provider == "openai":
            return "https://api.openai.com/v1"
        if provider == "anthropic":
            return "https://api.anthropic.com"
        if provider == "gemini":
            return "https://generativelanguage.googleapis.com"
        raise SceneGenerationError(f"Proveedor sin URL base: {provider}")

    def _resolved_model(self, provider: str) -> str:
        if self.model:
            return self.model
        env_models = {
            "ollama": os.environ.get("OLLAMA_MODEL"),
            "vllm": os.environ.get("VLLM_MODEL"),
            "openai": os.environ.get("OPENAI_MODEL"),
            "anthropic": os.environ.get("ANTHROPIC_MODEL"),
            "gemini": os.environ.get("GEMINI_MODEL") or os.environ.get("GOOGLE_MODEL"),
        }
        if env_models.get(provider):
            return str(env_models[provider])
        if provider in {"ollama", "vllm"}:
            return self.settings.local_llm_model
        if provider == "openai":
            return "gpt-4o-mini"
        if provider == "anthropic":
            return "claude-sonnet-4-5"
        if provider == "gemini":
            return "gemini-2.0-flash"
        raise SceneGenerationError(f"Proveedor sin modelo por defecto: {provider}")

    def _resolved_api_key(self, provider: str) -> str | None:
        if self.api_key:
            return self.api_key
        env_keys = {
            "vllm": ("VLLM_API_KEY",),
            "openai": ("OPENAI_API_KEY",),
            "anthropic": ("ANTHROPIC_API_KEY",),
            "gemini": ("GEMINI_API_KEY", "GOOGLE_API_KEY"),
        }
        for variable in env_keys.get(provider, ()):
            value = os.environ.get(variable)
            if value:
                return value
        settings_keys = {
            "openai": self.settings.openai_api_key,
            "anthropic": self.settings.anthropic_api_key,
            "gemini": self.settings.gemini_api_key,
        }
        resolved = settings_keys.get(provider)
        if provider in {"openai", "anthropic", "gemini"} and not resolved:
            raise SceneGenerationError(
                f"Falta la API key para el proveedor {provider}"
            )
        return resolved

    def _ollama_url(self) -> str:
        base = self._resolved_base_url("ollama")
        if base.endswith("/v1"):
            base = base[:-3]
        return f"{base}/api/chat"

    def _openai_compatible_url(self, provider: str) -> str:
        base = self._resolved_base_url(provider)
        if base.endswith("/chat/completions"):
            return base
        if base.endswith("/v1"):
            return f"{base}/chat/completions"
        return f"{base}/v1/chat/completions"

    def _anthropic_url(self) -> str:
        base = self._resolved_base_url("anthropic")
        if base.endswith("/v1/messages") or base.endswith("/messages"):
            return base
        if base.endswith("/v1"):
            return f"{base}/messages"
        return f"{base}/v1/messages"

    def _gemini_url(self, model: str) -> str:
        base = self._resolved_base_url("gemini")
        if base.endswith("/v1beta"):
            base = base[: -len("/v1beta")]
        return f"{base}/v1beta/models/{model}:generateContent"

    def _post_json(
        self,
        url: str,
        payload: Mapping[str, Any],
        *,
        headers: Mapping[str, str] | None = None,
        params: Mapping[str, str] | None = None,
    ) -> Mapping[str, Any]:
        client = self.http_client
        owned = client is None
        if client is None:
            client = httpx.Client(timeout=self.timeout)
        try:
            response = client.post(
                url,
                json=dict(payload),
                headers=dict(headers or {}),
                params=dict(params or {}),
            )
        except httpx.HTTPError as exc:
            raise LLMProviderError(f"No se pudo conectar con el proveedor LLM: {exc}") from exc
        finally:
            if owned:
                client.close()

        if response.status_code >= 400:
            body = response.text[:500]
            raise LLMProviderError(
                f"El proveedor LLM respondió HTTP {response.status_code}: {body}"
            )
        try:
            data = response.json()
        except ValueError as exc:
            raise LLMProviderError("El proveedor LLM no devolvió JSON válido") from exc
        if not isinstance(data, Mapping):
            raise LLMProviderError("El proveedor LLM devolvió un JSON no soportado")
        return data

    def complete(
        self,
        prompt: str,
        *,
        system: str | None = None,
        provider: str | None = None,
        model: str | None = None,
    ) -> str:
        """Send one completion request and return the raw model text."""

        resolved_provider = canonical_provider(provider or self.provider)
        if resolved_provider == "template":
            raise SceneGenerationError(
                "El proveedor 'template' no usa LLM; llama a build_technical_explainer_scene_html"
            )
        resolved_model = model or self._resolved_model(resolved_provider)
        messages: list[dict[str, str]] = []
        if system:
            messages.append({"role": "system", "content": system})
        messages.append({"role": "user", "content": prompt})

        if resolved_provider == "ollama":
            payload = {
                "model": resolved_model,
                "messages": messages,
                "stream": False,
                "options": {"temperature": 0.2, "num_predict": 4096},
            }
            data = self._post_json(self._ollama_url(), payload)
            content = _content_from_ollama(data)
        elif resolved_provider in {"vllm", "openai"}:
            headers: dict[str, str] = {}
            api_key = self._resolved_api_key(resolved_provider)
            if api_key:
                headers["Authorization"] = f"Bearer {api_key}"
            payload = {
                "model": resolved_model,
                "messages": messages,
                "temperature": 0.2,
                "max_tokens": 4096,
            }
            data = self._post_json(
                self._openai_compatible_url(resolved_provider),
                payload,
                headers=headers,
            )
            content = _content_from_openai(data)
        elif resolved_provider == "anthropic":
            api_key = self._resolved_api_key("anthropic")
            payload = {
                "model": resolved_model,
                "max_tokens": 4096,
                "temperature": 0.2,
                "messages": [{"role": "user", "content": prompt}],
            }
            if system:
                payload["system"] = system
            data = self._post_json(
                self._anthropic_url(),
                payload,
                headers={
                    "x-api-key": str(api_key),
                    "anthropic-version": "2023-06-01",
                },
            )
            content = _content_from_anthropic(data)
        elif resolved_provider == "gemini":
            api_key = self._resolved_api_key("gemini")
            payload = {
                "contents": [{"role": "user", "parts": [{"text": prompt}]}],
                "generationConfig": {
                    "temperature": 0.2,
                    "maxOutputTokens": 4096,
                },
            }
            if system:
                payload["system_instruction"] = {"parts": [{"text": system}]}
            data = self._post_json(
                self._gemini_url(resolved_model),
                payload,
                params={"key": str(api_key)},
            )
            content = _content_from_gemini(data)
        else:
            raise SceneGenerationError(f"Proveedor LLM no soportado: {resolved_provider}")

        content = content.strip()
        if not content:
            raise LLMProviderError(
                f"El proveedor {resolved_provider} devolvió una respuesta vacía"
            )
        return content

    def generate_scene_html(
        self,
        title: str,
        words: Sequence[object] | None = None,
        start_ms: int = DEFAULT_START_MS,
        end_ms: int = DEFAULT_END_MS,
        *,
        cues: Sequence[object] | None = None,
        word_timestamps: Sequence[object] | None = None,
        subtitle: str = "",
        eyebrow: str = DEFAULT_EYEBROW,
        duration_ms: int | None = None,
        width: int = DEFAULT_WIDTH,
        height: int = DEFAULT_HEIGHT,
        theme: str = DEFAULT_THEME,
        metrics: Sequence[object] | Mapping[str, Any] | None = None,
        accent: str = DEFAULT_ACCENT,
        instructions: str = "",
        provider: str | None = None,
        model: str | None = None,
        words_are_absolute: bool | None = None,
    ) -> str:
        """Generate one self-contained scene document ready for validation."""

        if duration_ms is not None:
            invalid_duration = (
                isinstance(duration_ms, bool)
                or not isinstance(duration_ms, int)
                or duration_ms <= 0
            )
            if invalid_duration:
                raise ValueError("duration_ms debe ser un entero > 0")
            end_ms = start_ms + duration_ms
        if end_ms <= start_ms:
            raise ValueError("end_ms debe ser mayor que start_ms")

        selected_words = _first_not_none(words, cues, word_timestamps)
        word_sequence = selected_words if isinstance(selected_words, Sequence) else None
        resolved_provider = canonical_provider(provider or self.provider)

        if resolved_provider == "template":
            return build_technical_explainer_scene_html(
                title,
                word_sequence,
                start_ms,
                end_ms,
                subtitle=subtitle,
                eyebrow=eyebrow,
                width=width,
                height=height,
                theme=theme,
                metrics=metrics,
                accent=accent,
                words_are_absolute=words_are_absolute,
            )

        prompt = build_scene_prompt(
            title,
            word_sequence,
            start_ms,
            end_ms,
            subtitle=subtitle,
            eyebrow=eyebrow,
            width=width,
            height=height,
            theme=theme,
            metrics=metrics,
            instructions=instructions,
            words_are_absolute=words_are_absolute,
        )
        system = build_system_prompt(width, height, theme)
        raw_response = self.complete(
            prompt,
            system=system,
            provider=resolved_provider,
            model=model,
        )
        html = extract_html_document(raw_response)
        normalized = normalize_word_cues(
            word_sequence,
            start_ms,
            end_ms,
            absolute=words_are_absolute,
        )
        html = inject_harness(html)
        return embed_word_cues(html, normalized)

    def generate_scene(
        self,
        project_id: str,
        scene_index: int,
        title: str,
        words: Sequence[object] | None = None,
        start_ms: int = DEFAULT_START_MS,
        end_ms: int = DEFAULT_END_MS,
        *,
        workspace: WorkspaceManager,
        validator: SceneValidator | None = None,
        prompt_used: str = "",
        **scene_options: Any,
    ) -> Scene:
        """Generate, persist and validate one scene in a single call."""

        target_validator = validator or self.validator
        if target_validator is None:
            raise SceneGenerationError("Se requiere un SceneValidator para persistir la escena")

        duration_override = scene_options.get("duration_ms")
        effective_end_ms = (
            start_ms + duration_override
            if isinstance(duration_override, int) and not isinstance(duration_override, bool)
            else end_ms
        )
        html = self.generate_scene_html(
            title,
            words,
            start_ms,
            effective_end_ms,
            **scene_options,
        )
        width = int(scene_options.get("width", target_validator.width))
        height = int(scene_options.get("height", target_validator.height))
        return target_validator.validate_and_save(
            project_id,
            scene_index,
            html,
            start_ms,
            effective_end_ms,
            title=title,
            prompt_used=prompt_used,
            width=width,
            height=height,
            workspace=workspace,
        )


