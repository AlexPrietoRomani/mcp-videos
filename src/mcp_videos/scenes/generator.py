class SceneGenerationError(RuntimeError):
    """Raised when a scene cannot be generated by the configured provider."""


class LLMProviderError(SceneGenerationError):
    """Raised when a local or remote LLM returns an unusable response."""


def canonical_provider(provider: str) -> str:
    """Normalize provider aliases to one of :data:`PROVIDERS`."""

    key = str(provider).strip().lower()
    resolved = _PROVIDER_ALIASES.get(key)
    if resolved is None:
        raise SceneGenerationError(
            f"Proveedor LLM no soportado: {provider!r}; use uno de {', '.join(PROVIDERS)}"
        )
    return resolved


def _json_for_html(value: object) -> str:
    payload = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return (
        payload.replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("&", "\\u0026")
    )


def _read_number(mapping: Mapping[str, Any], keys: Sequence[str]) -> float | None:
    for key in keys:
        value = mapping.get(key)
        if value is None or isinstance(value, bool):
            continue
        try:
            number = float(value)
        except (TypeError, ValueError):
            continue
        if number == number and number not in (float("inf"), float("-inf")):
            return number
    return None


def _word_mapping(item: object) -> Mapping[str, Any]:
    if isinstance(item, WordTimestamp):
        return item.model_dump()
    model_dump = getattr(item, "model_dump", None)
    if callable(model_dump):
        dumped = model_dump()
        if isinstance(dumped, Mapping):
            return dumped
    if isinstance(item, Mapping):
        return item
    raise SceneGenerationError(f"Cue de palabra no soportado: {item!r}")


def normalize_word_cues(
    words: Sequence[object] | None,
    scene_start_ms: int = 0,
    scene_end_ms: int | None = None,
    *,
    absolute: bool | None = None,
) -> list[dict[str, Any]]:
    """Convert domain/mapping cues into scene-local JSON-friendly dictionaries."""

    if words is None:
        return []
    if isinstance(scene_start_ms, bool) or not isinstance(scene_start_ms, int):
        raise ValueError("scene_start_ms debe ser un entero")
    if scene_start_ms < 0:
        raise ValueError("scene_start_ms debe ser >= 0")
    if scene_end_ms is not None and scene_end_ms <= scene_start_ms:
        raise ValueError("scene_end_ms debe ser mayor que scene_start_ms")

    entries = [_word_mapping(item) for item in words]
    if absolute is None:
        starts = [
            number
            for number in (
                _read_number(entry, ("start_ms", "startMs", "start")) for entry in entries
            )
            if number is not None
        ]
        absolute = scene_start_ms > 0 and bool(starts) and min(starts) >= scene_start_ms

    duration = None
    if scene_end_ms is not None:
        duration = scene_end_ms - scene_start_ms

    cues: list[dict[str, Any]] = []
    for entry in entries:
        start = _read_number(entry, ("start_ms", "startMs", "start"))
        end = _read_number(entry, ("end_ms", "endMs", "end"))
        if start is None or end is None:
            continue

        absolute_start = start
        absolute_end = end
        local_start = start - scene_start_ms if absolute else start
        local_end = end - scene_start_ms if absolute else end

        if duration is not None:
            local_start = min(duration, max(0.0, local_start))
            local_end = min(duration, max(0.0, local_end))
        if local_end <= local_start:
            local_end = local_start + 1

        word = str(
            entry.get("word")
            or entry.get("text")
            or entry.get("label")
            or ""
        ).strip()
        confidence = _read_number(entry, ("confidence",))
        cue: dict[str, Any] = {
            "word": word,
            "start_ms": round(local_start),
            "end_ms": round(local_end),
            "absolute_start_ms": round(absolute_start),
            "absolute_end_ms": round(absolute_end),
        }
        if confidence is not None:
            cue["confidence"] = max(0.0, min(1.0, confidence))
        line_id = entry.get("line_id")
        if isinstance(line_id, int) and not isinstance(line_id, bool):
            cue["line_id"] = line_id
        cues.append(cue)
    return cues


def extract_html_document(raw_response: str) -> str:
    """Extract a complete ``<!DOCTYPE html>...</html>`` document from an LLM reply."""

    if not isinstance(raw_response, str):
        raise TypeError("raw_response debe ser una cadena de texto")
    text = raw_response.lstrip("\ufeff").strip()
    if not text:
        raise ValueError("La respuesta del modelo está vacía")

    lower = text.lower()
    doctype_index = lower.find("<!doctype")
    html_index = lower.find("<html")
    starts = [index for index in (doctype_index, html_index) if index >= 0]
    if not starts:
        raise ValueError("La respuesta del modelo no contiene un documento HTML válido")

    start = min(starts)
    end = lower.rfind("</html>")
    if end < 0 or end + len("</html>") <= start:
        raise ValueError("La respuesta del modelo no contiene un documento HTML cerrado")
    if "<html" not in lower[start:end]:
        raise ValueError("La respuesta del modelo no contiene un documento HTML válido")

    return text[start : end + len("</html>")].strip()


def _format_seconds(value: int) -> str:
    return f"{value / 1000.0:.3f}s"


